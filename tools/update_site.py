"""Writes the game list of site/index.html from crates/core/presets.json: python3 tools/update_site.py"""

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LABELS = {
    "en": {"AltLeft": "Left Alt", "ControlRight": "Right Ctrl", "CapsLock": "Caps Lock", "Backquote": "`",
           "Mouse5": "Mouse 5", "none": "no key", "open": "open mic"},
    "fr": {"AltLeft": "Alt gauche", "ControlRight": "Ctrl droit", "CapsLock": "Verr. Maj", "Backquote": "²",
           "Mouse5": "Souris 5", "none": "pas de touche", "open": "micro ouvert"},
}


def key_label(code, lang):
    if code in LABELS[lang]:
        return LABELS[lang][code]
    match = re.fullmatch(r"Key(.)", code)
    return match.group(1) if match else code


def items(presets, lang):
    out = []
    for p in sorted(presets, key=lambda p: p["name"].lower()):
        keys = ", ".join(key_label(k, lang) for k in p["keys"]) or LABELS[lang]["none"]
        if p.get("ptt_disabled_by_default"):
            keys += f" · {LABELS[lang]['open']}"
        cls = "" if p["key_verified"] else ' class="unsure"'
        out.append(f'        <li>{html.escape(p["name"])} <span{cls}>{html.escape(keys)}</span></li>')
    return out


def main():
    presets = json.loads((ROOT / "crates/core/presets.json").read_text(encoding="utf-8"))
    block = ["      <!-- games:start (generated by tools/update_site.py) -->"]
    for lang in ("en", "fr"):
        block.append(f'      <ul class="games" lang="{lang}">')
        block += items(presets, lang)
        block.append("      </ul>")
    block.append("      <!-- games:end -->")
    page = ROOT / "site/index.html"
    text = page.read_text(encoding="utf-8")
    text = re.sub(r" *<!-- games:start.*?<!-- games:end -->", "\n".join(block), text, flags=re.S)
    page.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
